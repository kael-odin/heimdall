/**
 * HTML 转义 —— **唯一实现**
 *
 * 原本在 9 个文件里各写了一份，而且**分成了两种**：6 份转义 `& < "`，
 * 3 份还多转义了 `>`。两种都能用，但"同一个项目里两套转义规则"本身就是个隐患 ——
 * 下次有人只改了其中一套、或者把一个 `esc` 从 A 文件搬到 B 文件，行为就悄悄变了。
 *
 * 这里取更严格的那一套（多转 `>`），因为它在所有上下文里都安全，
 * 而少转一个字符的收益为零。
 */
export const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');
