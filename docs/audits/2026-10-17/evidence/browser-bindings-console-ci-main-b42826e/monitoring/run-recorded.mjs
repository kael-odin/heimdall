import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createHash, randomUUID } from 'node:crypto';
import { closeSync, mkdirSync, openSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const OUT = dirname(fileURLToPath(import.meta.url));
const [tag, executable, ...args] = process.argv.slice(2);
assert.ok(/^[a-z0-9-]+$/.test(tag)); assert.ok(executable);
const directory = join(OUT, tag + '-' + randomUUID()); mkdirSync(directory);
const info = path => { const bytes = readFileSync(path); return { bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') }; };
const writeJson = (name, value) => writeFileSync(join(directory, name), JSON.stringify(value, null, 2) + '\n', { flag: 'wx' });
const invocation = { executable, args, cwd: process.cwd(), startedAt: new Date().toISOString() };
writeJson('command.json', invocation);
console.log(JSON.stringify({ status: 'started', directory, ...invocation }));
const stdout = openSync(join(directory, 'stdout.log'), 'wx'), stderr = openSync(join(directory, 'stderr.log'), 'wx');
const child = spawn(executable, args, { windowsHide: true, stdio: ['ignore', stdout, stderr] });
const result = await new Promise(resolve => { child.once('error', error => resolve({ code: null, signal: null, error: String(error) })); child.once('close', (code, signal) => resolve({ code, signal, error: null })); });
closeSync(stdout); closeSync(stderr);
const record = { ...invocation, finishedAt: new Date().toISOString(), ...result, stdout: { path: 'stdout.log', ...info(join(directory, 'stdout.log')) }, stderr: { path: 'stderr.log', ...info(join(directory, 'stderr.log')) } };
writeJson('exitcode.json', record); console.log(JSON.stringify({ directory, ...record }, null, 2));
process.exitCode = result.code ?? 1;
